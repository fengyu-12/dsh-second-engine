// 为什么抽出来而不在这几处各写一遍：抄 4 遍 ⇒ 下次出现第 5 个信号源必然漏掉。
// 同一形状的错今天在 UI 里重复了四次，都是「只改眼前那一处」。
//
// 措辞约束（用户裁定）：不是「停手」，是「必须回应」——
// 停手不可验证，回应可验证：回复里能不能看出他核对了什么、判成了哪一类。
// 与各条原有的「不要在本轮回复中提及这条提醒」不冲突：不暴露机制，但处理动作必须发生。
//
// 工单 Z1（2026-11-06）：这段收尾从此**只用于没有回执校验的注入源**（policy-watch 等）。
// mood-watch 不再挂这句 —— 它的「必须回应」改由状态机强制：注入时带事件 ID，
// 下一轮解析 [MW_ACK] 回执，缺字段就再插提醒、连续两次缺就把后续计划标记为待确认。
// 原因（外部复核意见）：高频、位置固定、措辞完全相同的文本会变成模板噪音；
// 光有这句，模型输出了套话也照样继续原计划。
